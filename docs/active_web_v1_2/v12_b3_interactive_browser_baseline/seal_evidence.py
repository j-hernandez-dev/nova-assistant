def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def write(name, data):
    (OUT/name).write_text(json.dumps(data, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')


def pin(path):
    return dict(path=path.relative_to(ROOT).as_posix(), bytes=path.stat().st_size,
                sha256=hashlib.sha256(path.read_bytes()).hexdigest())


def suite(name):
    xml=ET.parse(OUT/name).getroot(); cases=xml.findall('.//testcase')
    failed=[c.attrib for c in cases if c.find('failure') is not None]
    errors=[c.attrib for c in cases if c.find('error') is not None]
    skipped=[c.attrib for c in cases if c.find('skipped') is not None]
    return dict(xml=name, tests=len(cases), passed=len(cases)-len(failed)-len(errors)-len(skipped),
                failed=len(failed), errors=len(errors), skipped=len(skipped),
                failedCases=failed, errorCases=errors, cases=[c.attrib for c in cases])


