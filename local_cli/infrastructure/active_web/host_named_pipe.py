"""Windows-only private IPC transport. Lazy native APIs, no Core imports."""
from __future__ import annotations

import ctypes
from ctypes import wintypes
import os
import struct
import time

from .host_ipc_protocol import HostIpcError, IpcCode, MAX_FRAME_BYTES, decode, require


class NamedPipeTransport:
    def __init__(self, handle, api):
        self.handle, self.api = handle, api

    @staticmethod
    def native():
        require(os.name == 'nt', IpcCode.PROCESS_START_FAILED)
        k = ctypes.WinDLL('kernel32', use_last_error=True)
        k.CreateFileW.argtypes = (wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD, ctypes.c_void_p,
                                 wintypes.DWORD, wintypes.DWORD, wintypes.HANDLE)
        k.CreateFileW.restype = wintypes.HANDLE
        k.WaitNamedPipeW.argtypes = (wintypes.LPCWSTR, wintypes.DWORD)
        k.WaitNamedPipeW.restype = wintypes.BOOL
        k.GetNamedPipeServerProcessId.argtypes = (wintypes.HANDLE, ctypes.POINTER(wintypes.ULONG))
        k.GetNamedPipeServerProcessId.restype = wintypes.BOOL
        k.CreateEventW.argtypes = (ctypes.c_void_p, wintypes.BOOL, wintypes.BOOL, wintypes.LPCWSTR)
        k.CreateEventW.restype = wintypes.HANDLE
        for name in ('ReadFile', 'WriteFile'):
            f = getattr(k, name)
            f.argtypes = (wintypes.HANDLE, ctypes.c_void_p, wintypes.DWORD,
                          ctypes.POINTER(wintypes.DWORD), ctypes.c_void_p)
            f.restype = wintypes.BOOL
        k.GetOverlappedResult.argtypes = (wintypes.HANDLE, ctypes.c_void_p, ctypes.POINTER(wintypes.DWORD), wintypes.BOOL)
        k.GetOverlappedResult.restype = wintypes.BOOL
        k.CancelIoEx.argtypes = (wintypes.HANDLE, ctypes.c_void_p)
        k.CancelIoEx.restype = wintypes.BOOL
        k.WaitForSingleObject.argtypes = (wintypes.HANDLE, wintypes.DWORD)
        k.WaitForSingleObject.restype = wintypes.DWORD
        k.CloseHandle.argtypes = (wintypes.HANDLE,)
        k.CloseHandle.restype = wintypes.BOOL
        return k

    @classmethod
    def connect(cls, name, expected_pid, *, end, process, cancel=None):
        # Name is generated by composition, never model/page input. Local prefix only.
        from .host_ipc_protocol import ref
        ref(name, 'nova_browser_host')
        api = cls.native()
        path = '\\\\.\\pipe\\' + name
        while True:
            cls.check(end, process, cancel)
            # Overlapped, non-inheritable, impersonation limited to identification.
            handle = api.CreateFileW(path, 0xC0000000, 0, None, 3, 0x40110000, None)
            if handle != ctypes.c_void_p(-1).value:
                transport = cls(handle, api)
                pid = wintypes.ULONG()
                if not api.GetNamedPipeServerProcessId(handle, ctypes.byref(pid)) or pid.value != expected_pid:
                    transport.close()
                    raise HostIpcError(IpcCode.UNAUTHORIZED_CLIENT)
                return transport
            error = ctypes.get_last_error()
            if error not in (2, 231):
                raise HostIpcError(IpcCode.UNAUTHORIZED_CLIENT)
            # Connection discovery only; never retries a transmitted request.
            time.sleep(min(.005, max(0, end - time.monotonic())))

    @staticmethod
    def check(end, process=None, cancel=None):
        if cancel is not None and cancel.is_set():
            raise HostIpcError(IpcCode.CANCELLED)
        if process is not None and process.poll() is not None:
            raise HostIpcError(IpcCode.PROCESS_EXIT_UNEXPECTED)
        if time.monotonic() >= end:
            raise HostIpcError(IpcCode.TIMEOUT)

    def _io(self, count_or_bytes, *, read, end, process=None, cancel=None):
        require(self.handle is not None, IpcCode.DISCONNECTED)
        class Overlapped(ctypes.Structure):
            _fields_ = [('Internal', ctypes.c_size_t), ('InternalHigh', ctypes.c_size_t),
                        ('Offset', wintypes.DWORD), ('OffsetHigh', wintypes.DWORD), ('hEvent', wintypes.HANDLE)]
        event = self.api.CreateEventW(None, True, False, None)
        require(bool(event), IpcCode.DISCONNECTED)
        overlapped = Overlapped(0, 0, 0, 0, event)
        buffer = ctypes.create_string_buffer(count_or_bytes if read else bytes(count_or_bytes))
        count = count_or_bytes if read else len(count_or_bytes)
        done = wintypes.DWORD()
        pending = False
        try:
            self.check(end, process, cancel)
            f = self.api.ReadFile if read else self.api.WriteFile
            ok = f(self.handle, buffer, count, ctypes.byref(done), ctypes.byref(overlapped))
            if not ok:
                require(ctypes.get_last_error() == 997, IpcCode.DISCONNECTED)
                pending = True
                while self.api.WaitForSingleObject(event, 0) == 258:
                    self.check(end, process, cancel)
                    time.sleep(min(.005, max(0, end - time.monotonic())))
                require(self.api.GetOverlappedResult(self.handle, ctypes.byref(overlapped), ctypes.byref(done), False),
                        IpcCode.DISCONNECTED)
                pending = False
            self.check(end, process, cancel)
            require(done.value > 0, IpcCode.DISCONNECTED)
            return buffer.raw[:done.value] if read else done.value
        finally:
            if pending:
                # OVERLAPPED/buffer must remain alive until canceled IO completes.
                self.api.CancelIoEx(self.handle, ctypes.byref(overlapped))
                self.api.GetOverlappedResult(self.handle, ctypes.byref(overlapped), ctypes.byref(done), True)
            self.api.CloseHandle(event)

    def write(self, frame, *, end, process=None, cancel=None):
        at = 0
        while at < len(frame):
            at += self._io(frame[at:], read=False, end=end, process=process, cancel=cancel)

    def read_exact(self, count, *, end, process=None, cancel=None):
        result = bytearray()
        while len(result) < count:
            result.extend(self._io(count-len(result), read=True, end=end, process=process, cancel=cancel))
        return bytes(result)

    def receive(self, *, end, process=None, cancel=None, decoder=decode):
        header = self.read_exact(4, end=end, process=process, cancel=cancel)
        length = struct.unpack('<I', header)[0]
        require(0 < length <= MAX_FRAME_BYTES, IpcCode.OVERSIZED_FRAME)
        return decoder(self.read_exact(length, end=end, process=process, cancel=cancel))

    def close(self):
        if self.handle is not None:
            self.api.CloseHandle(self.handle)
            self.handle = None
